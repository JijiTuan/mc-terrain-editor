/**
 * probe-hooks.js — 自动化探针的短路钩子（默认空置）
 *
 * ============ 为什么需要这个文件 ============
 *
 * 「交互真的生效了吗」这类断言，必须配一次反向对照才有说服力：
 * 把功能故意打掉，同一套操作必须失败。否则一个永远返回 true 的探针
 * 也会「通过」，而它什么也没证明。
 *
 * 但短路不能靠事后替换 app.onCellEdit —— 交互控制器在构造时就把
 * onCellEdit 回调捕获进了闭包，事后替换 App 上的同名方法不会被调用到。
 * 所以改为在 App 构造期间提供一个钩子表：钩子存在时由钩子决定结果，
 * 返回 undefined 表示「放行给正常逻辑」。
 *
 * 这个文件默认不注册任何钩子，加载它等于什么都没做。
 * 探针会用 page.addInitScript 在页面脚本执行前把 window.__MC_PROBE_HOOKS__
 * 设好，于是钩子便能被 App 读到。
 *
 * 注意：不要在这个文件里放任何业务逻辑 —— 它是测试脚手架，
 * 一旦带上真实行为，生产环境就多了一条只在测试时才不同的代码路径。
 */
(function () {
  'use strict'
  if (typeof window === 'undefined') return
  // 显式声明契约：App 读的就是这个名字。
  // 探针若已注入过钩子则保持不变；否则留 null（=不使用钩子）。
  if (!('__MC_PROBE_HOOKS__' in window)) {
    window.__MC_PROBE_HOOKS__ = null
  }
})()
